# Backwards-compatible alias for the old public name (<j0> coefficients only).
FORM_FACTOR_COEFFICIENTS = RADIAL_INTEGRAL_COEFFICIENTS

_ION_RE = re.compile(r"^([A-Z][a-z]?)\s*(\d*)\s*([+-]?)([a-c]?)$")


def _normalize_ion(ion: str) -> str:
    """Map a user-facing ion label onto a key of RADIAL_INTEGRAL_COEFFICIENTS.

    'Fe2+' -> 'Fe2', 'Cu2' -> 'Cu2', 'Fe' -> 'Fe0', 'Ir0a' -> 'Ir0a'.
    Returns '' when the label cannot be parsed.
    """
    if not isinstance(ion, str):
        return ""
    key = ion.strip()
    if key in RADIAL_INTEGRAL_COEFFICIENTS:
        return key
    m = _ION_RE.match(key)
    if not m:
        return ""
    element, charge, sign, config = m.groups()
    if sign == "-":          # no anion entries are tabulated
        return ""
    candidate = f"{element}{charge or '0'}{config}"
    return candidate if candidate in RADIAL_INTEGRAL_COEFFICIENTS else ""


def _gaussian_expansion(coeffs: Tuple[float, ...], s2):
    A, a, B, b, C, c, D, d, E = coeffs
    return (A * np.exp(-a * s2) + B * np.exp(-b * s2)
            + C * np.exp(-c * s2) + D * np.exp(-d * s2) + E)


def _warn_unknown(ion: str) -> None:
    logger.warning(
        f"Ion '{ion}' is not in the magnetic form-factor table; using f(Q) = 1 "
        f"(no form factor). Spell it like 'Fe2+' / 'Fe2', or 'Fe' for the neutral "
        f"atom; 5d ions need the configuration suffix, e.g. 'Ir0a'.")


def get_j0(ion: str, Q_mag):
    """<j0>(s) for `ion` at |Q| in 1/Angstrom (s = |Q| / 4pi). 1.0 if unknown."""
    key = _normalize_ion(ion)
    if not key:
        _warn_unknown(ion)
        return 1.0
    s2 = (np.asarray(Q_mag, dtype=float) / (4.0 * np.pi)) ** 2
    return _gaussian_expansion(RADIAL_INTEGRAL_COEFFICIENTS[key][0], s2)


def get_j2(ion: str, Q_mag):
    """<j2>(s) for `ion` at |Q| in 1/Angstrom. 0.0 if unknown.

    NB the tabulated expansion is multiplied by s^2, as in Sunny/ITC.
    """
    key = _normalize_ion(ion)
    if not key:
        _warn_unknown(ion)
        return 0.0
    s2 = (np.asarray(Q_mag, dtype=float) / (4.0 * np.pi)) ** 2
    return _gaussian_expansion(RADIAL_INTEGRAL_COEFFICIENTS[key][1], s2) * s2


def get_form_factor(ion: str, Q_mag, g: float = 2.0):
    """f(Q) = <j0> + ((2 - g) / g) <j2>, the dipole approximation.

    At the default g = 2 this is exactly <j0>, matching Sunny's
    `compute_form_factor` with `g_lande = 2`.
    """
    key = _normalize_ion(ion)
    if not key:
        _warn_unknown(ion)
        return 1.0
    j0 = get_j0(key, Q_mag)
    if g == 2.0:
        return j0
    return j0 + ((2.0 - g) / g) * get_j2(key, Q_mag)
