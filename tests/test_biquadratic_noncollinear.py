"""Biquadratic exchange off the collinear axis, and terms the dipole engine must refuse.

Until 2026-10-29 the symbolic build dropped part of B (S_i.S_j)^2 in two cases, with
only a WARNING ("Construct TwogH2: Dropped N terms"):

* on a bond carrying NO bilinear coupling: gen_HM's Fourier lookup only had entries
  for pairs where Jex, DM or Kex is non-zero, so every cross-site word went;
* on an intercell bond between DIFFERENTLY oriented sites: the (j, i)-ordered words
  of S_i^a S_j^a S_i^b S_j^b have no entry when j is an image. Their coefficient
  (v_i.t_j)(t_i.v_j) vanishes for collinear moments and for equally rotated sites,
  which is why `test_biquadratic_reduces_to_exact_collinear_bilinear` (collinear) and
  SW28 (J_eff mapping, no biquadratic term) could not see it.

The oracles, none of which is the engine itself:

* Sunny 0.8.1 `:dipole_uncorrected` on the 120-degree triangular AFM in a 3x3
  supercell, where every bond leaving the supercell joins differently oriented sites
  (`tests/data_biquadratic_noncollinear_sunny.json`, regenerated by
  `tests/biquadratic_noncollinear_sunny_reference.jl`);
* gauge invariance: moving a site by a lattice vector, bond offsets adjusted, is the
  same crystal and the same Hamiltonian, so the spectrum of H(q) must not move. The
  defect moved it by 0.2 meV;
* continuity: a 1e-12 Heisenberg on a bare biquadratic bond cannot change the physics,
  but it used to switch the biquadratic's cross-site words back on.

`pair_operator` was dropped in dipole mode without even a warning; it now raises.
"""
import copy
import json
import os

import numpy as np
import pytest

import magcalc as mc
from magcalc.generic_model import GenericSpinModel

HERE = os.path.dirname(os.path.abspath(__file__))


def _calc(cfg, S, tag):
    m = GenericSpinModel(copy.deepcopy(cfg))
    th, ph = m.generate_magnetic_structure()
    m.set_magnetic_structure(th, ph)
    return mc.MagCalc(spin_model_module=m, spin_magnitude=S, cache_mode="none",
                      cache_file_base=tag, hamiltonian_params=[])


def _spectrum(calc, q_cart):
    """Eigenvalues of g.H2(q), sorted: gauge-invariant even off a minimum."""
    h = calc._build_h_stack(np.asarray(q_cart, float), float(calc.spin_magnitude))
    ev = [np.linalg.eigvals(m) for m in h]
    return np.array([e[np.lexsort((np.round(e.imag, 9), np.round(e.real, 9)))] for e in ev])


# --------------------------------------------------------------------------
# Two-site chain, non-collinear, biquadratic on the INTERCELL bond
# --------------------------------------------------------------------------
LAT = [[6.0, 0, 0], [0, 9.0, 0], [0, 0, 9.0]]
DIRS = [[0.3, -0.5, 0.81], [-0.6, 0.2, 0.77]]   # neither collinear nor equal
QS_RLU = [[0.0, 0, 0], [0.13, 0.1, 0], [0.31, 0, 0.2], [0.5, 0, 0], [0.77, 0.3, 0]]


def _chain(b_shift=0, biq_intercell=-0.06, biq_intracell=0.0, extra=()):
    """A at x = 0, B at x = 1/2 + b_shift. Bond offsets are written for b_shift = 0 and
    adjusted, so every b_shift describes the same crystal and Hamiltonian."""
    def bonds(t, value, off_ab):
        o = np.array(off_ab) - [b_shift, 0, 0]
        return [{"type": t, "pair": ["A", "B"], "rij_offset": o.tolist(), "value": value},
                {"type": t, "pair": ["B", "A"], "rij_offset": (-o).tolist(), "value": value}]
    inter = bonds("heisenberg", 1.0, [0, 0, 0]) + bonds("heisenberg", 0.4, [-1, 0, 0])
    if biq_intercell:
        inter += bonds("biquadratic", biq_intercell, [-1, 0, 0])
    if biq_intracell:
        inter += bonds("biquadratic", biq_intracell, [0, 0, 0])
    inter += list(extra)
    return {"crystal_structure": {"lattice_vectors": LAT, "atoms_uc": [
                {"label": "A", "pos": [0.0, 0, 0], "spin_S": 1.5},
                {"label": "B", "pos": [0.5 + b_shift, 0, 0], "spin_S": 1.5}]},
            "interactions": inter, "parameters": {}, "parameter_order": [],
            "magnetic_structure": {"type": "pattern", "pattern_type": "generic",
                                   "directions": DIRS},
            "calculation": {"on_imaginary": "off"}, "tasks": {}}


def _q_cart():
    B = 2 * np.pi * np.linalg.inv(np.array(LAT, float)).T
    return np.array(QS_RLU) @ B


def test_intercell_biquadratic_is_gauge_invariant():
    """Moving B by -a1 turns the intercell bond into an intra-cell one, where the old
    lookup had both operator orders. The spectrum must not care: it moved by 0.2 meV
    on the 2026-10-29 synthetic model before the fix."""
    q = _q_cart()
    here = _spectrum(_calc(_chain(b_shift=0), 1.5, "biqg0"), q)
    moved = _spectrum(_calc(_chain(b_shift=-1), 1.5, "biqg1"), q)
    assert np.max(np.abs(here - moved)) < 1e-10
    # and the term must matter, or the identity proves nothing
    none = _spectrum(_calc(_chain(b_shift=0, biq_intercell=0.0), 1.5, "biqg_none"), q)
    assert np.max(np.abs(here - none)) > 1e-2


def test_biquadratic_on_a_bare_bond_is_continuous_in_J():
    """A biquadratic on a bond with no bilinear coupling, against the same plus
    J = 1e-12 there. The second used to restore the cross-site words the first lost."""
    def bare(eps):
        extra = [{"type": "biquadratic", "pair": p, "rij_offset": o, "value": 0.05}
                 for p, o in ((["A", "A"], [2, 0, 0]), (["A", "A"], [-2, 0, 0]))]
        if eps:
            extra += [{"type": "heisenberg", "pair": p, "rij_offset": o, "value": eps}
                      for p, o in ((["A", "A"], [2, 0, 0]), (["A", "A"], [-2, 0, 0]))]
        return _chain(biq_intercell=0.0, extra=extra)
    q = _q_cart()
    h0 = _calc(bare(0.0), 1.5, "bare0")._build_h_stack(q, 1.5)
    h1 = _calc(bare(1e-12), 1.5, "bare1")._build_h_stack(q, 1.5)
    assert np.max(np.abs(h0 - h1)) < 1e-10
    hn = _calc(_chain(biq_intercell=0.0), 1.5, "bare_none")._build_h_stack(q, 1.5)
    assert np.max(np.abs(h0 - hn)) > 1e-3


def test_unplaceable_quadratic_terms_raise(monkeypatch):
    """The build used to WARN and drop a quadratic term with no Fourier placement --
    that is how both biquadratic defects stayed silent. It now raises."""
    from magcalc import symbolic
    monkeypatch.setattr(symbolic, "_complete_fourier_lookup", lambda *a, **k: None)
    with pytest.raises(RuntimeError, match="no Fourier placement"):
        _calc(_chain(), 1.5, "biq_drop")


# --------------------------------------------------------------------------
# Sunny 0.8.1: 120-degree triangular AFM with a biquadratic, 3x3 supercell
# --------------------------------------------------------------------------
SUNNY = json.load(open(os.path.join(HERE, "data_biquadratic_noncollinear_sunny.json")))
TRI = [[3.0, 0, 0], [-1.5, 1.5 * np.sqrt(3), 0], [0, 0, 10.0]]


def _triangular_cfg():
    return {"crystal_structure": {
                "lattice_vectors": TRI, "magnetic_supercell": [3, 3, 1],
                "atoms_uc": [{"label": "A", "pos": [0.0, 0, 0], "spin_S": SUNNY["s"]}]},
            "interactions": {
                "symmetry_rules": [{"type": "heisenberg", "distance": 3.0,
                                    "value": SUNNY["J"]}],
                "biquadratic": [{"distance": 3.0, "value": SUNNY["B"]}]},
            "parameters": {}, "parameter_order": [],
            "magnetic_structure": {"type": "single_k", "k": [1 / 3, 1 / 3, 0],
                                   "axis": [0, 0, 1], "S0": [[1, 0, 0]]},
            "calculation": {"on_imaginary": "off"}, "tasks": {}}


@pytest.mark.slow
def test_noncollinear_biquadratic_matches_sunny():
    """Every band and the band-summed intensity at six generic q. Sunny's state was
    checked to be a minimum (minimize_energy! from it lowers nothing)."""
    calc = _calc(_triangular_cfg(), SUNNY["s"], "biq_tri")
    B = 2 * np.pi * np.linalg.inv(np.array(TRI, float)).T
    q = np.array(SUNNY["q_rlu"]) @ B
    res = calc.calculate_sqw(list(q))
    E = np.sort(np.real(np.asarray(res.energies)), axis=1)
    I = np.asarray(res.intensities).sum(axis=1)
    assert E == pytest.approx(np.array(SUNNY["bands"]), abs=1e-6)
    assert I == pytest.approx(np.array(SUNNY["total_intensity"]), rel=1e-5)


# --------------------------------------------------------------------------
# pair_operator: SU(N)/entangled only, refused in dipole mode
# --------------------------------------------------------------------------
def _pair_op_cfg(mode="dipole"):
    cfg = _chain(biq_intercell=0.0)
    cfg["interactions"] = {
        "heisenberg": [{"pair": p, "rij_offset": o, "value": 1.0} for p, o in (
            (["A", "B"], [0, 0, 0]), (["B", "A"], [0, 0, 0]),
            (["B", "A"], [1, 0, 0]), (["A", "B"], [-1, 0, 0]))],
        "pair_operator": [{"pair": ["A", "B"], "rij_offset": [0, 0, 0],
                           "poly": [0.0, 0.0, -0.4]},
                          {"pair": ["B", "A"], "rij_offset": [0, 0, 0],
                           "poly": [0.0, 0.0, -0.4]}]}
    cfg["magnetic_structure"]["directions"] = [[0, 0, 1], [0, 0, -1]]
    cfg["calculation"]["mode"] = mode
    return cfg


def test_pair_operator_raises_in_the_dipole_build():
    with pytest.raises(ValueError, match="pair_operator"):
        _calc(_pair_op_cfg(), 1.5, "pairop")


def test_pair_operator_raises_in_a_dipole_run(tmp_path):
    import yaml
    from magcalc.runner import run_calculation
    cfg = _pair_op_cfg()
    cfg["tasks"] = {"minimization": True, "dispersion": True}
    cfg["minimization"] = {"enabled": True, "method": "anneal", "num_starts": 1,
                           "n_sweeps": 50, "seed": 0}
    p = tmp_path / "pairop.yaml"
    p.write_text(yaml.safe_dump(cfg))
    with pytest.raises(ValueError, match="pair_operator"):
        run_calculation(str(p))


def test_models_without_pair_operator_are_not_refused():
    m = GenericSpinModel(copy.deepcopy(_chain()))
    m.reject_dipole_unsupported()   # no raise
